import { FileSystem } from "../fs/filesystem";
import { NativeKernel } from "./native";
export type TaskState =
  "runnable" | "running" | "waiting" | "terminated" | "cancelled";
export type Task = {
  pid: number;
  ppid: number;
  name: string;
  kind: string;
  state: TaskState;
  created: number;
  ended?: number;
  exitCode?: number;
  memoryBytes: number;
  controller: AbortController;
};
export type TraceEvent = {
  id: number;
  time: number;
  pid: number;
  layer: string;
  op: string;
  args: string;
  result: string;
  duration: number;
};
export type Descriptor = {
  pid: number;
  fd: number;
  path: string;
  mode: "r" | "w" | "rw";
  offset: number;
};
type TaskRecord = Omit<Task, "controller">;
export class Kernel {
  core = new NativeKernel();
  fs = new FileSystem(this.core);
  revision = 0;
  listeners = new Set<() => void>();
  private taskCache = new Map<number, Task>();
  private caller = 1;
  constructor() {
    this.core.onEvents = () => this.notify();
    this.fs.onChange = () => this.notify();
  }
  get started() {
    return this.core.info().started;
  }
  get currentPid() {
    return this.caller;
  }
  set currentPid(pid: number) {
    this.caller = pid;
    this.core.call("kernel.caller", { pid });
  }
  get tasks() {
    const rows = this.taskInfo(),
      ids = new Set(rows.map((t) => t.pid));
    for (const pid of this.taskCache.keys())
      if (!ids.has(pid)) this.taskCache.delete(pid);
    for (const row of rows) {
      let t = this.taskCache.get(row.pid);
      if (!t) {
        t = { ...row, controller: new AbortController() };
        this.taskCache.set(row.pid, t);
      } else Object.assign(t, row);
    }
    return this.taskCache;
  }
  get events() {
    return this.core.call<TraceEvent[]>("trace.list").value;
  }
  set events(events: TraceEvent[]) {
    if (events.length)
      throw Error("Trace records are generated by the WASM kernel");
    this.core.call("trace.clear");
    this.notify();
  }
  get fds() {
    return this.core.call<Descriptor[]>("fd.list").value;
  }
  set fds(fds: Descriptor[]) {
    this.core.call("fd.replace", { fds });
  }
  subscribe = (fn: () => void) => {
    this.listeners.add(fn);
    return () => {
      this.listeners.delete(fn);
    };
  };
  notify() {
    this.revision++;
    for (const l of this.listeners) l();
  }
  trace(
    pid: number,
    layer: string,
    op: string,
    args = "",
    result = "0",
    duration = 0,
  ) {
    this.core.call("trace.add", {
      pid,
      layer,
      name: op,
      args,
      result,
      duration,
    });
  }
  spawn(name: string, kind = "userspace", ppid = 1) {
    const row = this.core.call<TaskRecord>("task.spawn", {
      name,
      kind,
      ppid,
    }).value;
    const task = { ...row, controller: new AbortController() };
    this.taskCache.set(task.pid, task);
    return task;
  }
  state(task: Task, state: TaskState) {
    if (task.ended !== undefined) return;
    this.core.call("task.state", { pid: task.pid, state });
    Object.assign(task, this.tasks.get(task.pid));
  }
  finish(task: Task, code = 0) {
    if (task.ended !== undefined) return;
    this.core.call("task.finish", {
      pid: task.pid,
      code,
      cancelled: task.controller.signal.aborted,
    });
    Object.assign(task, this.tasks.get(task.pid));
  }
  cancel(pid: number) {
    const ids = this.core.call<number[]>("task.cancel", { pid }).value;
    const current = this.tasks;
    for (const id of ids) current.get(id)?.controller.abort();
  }
  memory(task: Task, bytes: number) {
    this.core.call("task.memory", { pid: task.pid, bytes });
    task.memoryBytes = bytes;
    this.notify();
  }
  async run<T>(
    name: string,
    kind: string,
    fn: (task: Task) => Promise<T> | T,
    parent = 1,
    signal?: AbortSignal,
  ) {
    const t = this.spawn(name, kind, parent);
    const abort = () => {
      if (t.ended === undefined) this.cancel(t.pid);
    };
    signal?.addEventListener("abort", abort, { once: true });
    try {
      if (signal?.aborted) throw Error("Interrupted");
      await new Promise<void>((r) => setTimeout(r, 0));
      this.state(t, "running");
      if (t.controller.signal.aborted) throw Error("Interrupted");
      const result = await fn(t);
      this.finish(t, 0);
      return result;
    } catch (e) {
      this.finish(t, t.controller.signal.aborted ? 130 : 1);
      throw e;
    } finally {
      signal?.removeEventListener("abort", abort);
    }
  }
  withPid<T>(pid: number, fn: () => T): T {
    const previous = this.currentPid;
    this.currentPid = pid;
    try {
      return fn();
    } finally {
      this.currentPid = previous;
    }
  }
  open(pid: number, path: string, mode: Descriptor["mode"] = "r") {
    return this.withPid(
      pid,
      () => this.core.call<number>("fd.open", { pid, path, mode }).value,
    );
  }
  read(pid: number, fd: number, count: number) {
    return this.withPid(
      pid,
      () => this.core.call("fd.read", { pid, fd, count }).data,
    );
  }
  write(pid: number, fd: number, data: Uint8Array) {
    this.withPid(pid, () => this.core.call("fd.write", { pid, fd }, data));
    this.fs.changed();
  }
  close(pid: number, fd: number) {
    this.core.call("fd.close", { pid, fd });
  }
  proc() {
    this.core.call("proc.mount");
    for (const name of ["tasks", "mounts", "runtime"])
      this.fs.dynamic.set("/proc/" + name, () =>
        new TextDecoder().decode(this.fs.peek("/proc/" + name)),
      );
    this.fs.changed();
  }
  taskInfo() {
    return this.core.call<TaskRecord[]>("task.list").value;
  }
}
